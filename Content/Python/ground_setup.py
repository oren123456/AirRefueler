"""Ground 6 km below the aircraft: a curved cap (planet radius 6360 km, 300 km radius so its rim is past the
horizon) at the planet top (SkyAtmosphere sits at z=-600000), mesh from Data/Generated/ground_cap.obj
(generated by Tools/ground_cap.py). Procedural material M_Ground (Custom HLSL, world-position based): farmland
patchwork with field borders, arid tan regions, towns; detail averages out with pixel footprint. Re-runnable."""
import os
import unreal
MATDIR = "/Game/AirRefueler/Sim/Materials"; MESHDIR = "/Game/AirRefueler/Sim/Meshes"; Z = -600000.0
FAR = (0.17, 0.14, 0.08)              # linear average ground colour -> SkyAtmosphere ground albedo (sRGB)
eal = unreal.EditorAssetLibrary; at = unreal.AssetToolsHelpers.get_asset_tools(); mel = unreal.MaterialEditingLibrary
eas = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
log = lambda s: unreal.log("[Ground] " + s)

CODE = r"""
struct G {
  float h(float2 p) { float3 p3 = frac(float3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return frac((p3.x + p3.y) * p3.z); }
  float vn(float2 p) { float2 i = floor(p); float2 f = frac(p); f = f * f * (3.0 - 2.0 * f);
    return lerp(lerp(h(i), h(i + float2(1, 0)), f.x), lerp(h(i + float2(0, 1)), h(i + float2(1, 1)), f.x), f.y); }
  float fbm(float2 p) { float s = 0, a = 0.5; for (int k = 0; k < 5; k++) { s += a * vn(p); p = p * 2.03 + 17.1; a *= 0.5; } return s / 0.97; }
};
G g;
float2 p = WP.xy / 100.0;                                   // metres
float dist = length(WP - Cam) / 100.0;
float2 fw = max(abs(ddx(p)), abs(ddy(p))); float px = max(max(fw.x, fw.y), 0.01);
float far = saturate(max(smoothstep(40.0, 160.0, px), smoothstep(15000.0, 60000.0, dist)));
// farmland vs arid
float farm = smoothstep(0.46, 0.60, g.fbm(p / 9000.0 + 3.7));
// field layout changes per 6 km block: orientation and field size
float2 blk = floor(p / 6000.0);
float hb = g.h(blk + 4.2);
float ang = (hb - 0.5) * 1.2;
float ca = cos(ang), sa = sin(ang);
float2 q = float2(ca * p.x - sa * p.y, sa * p.x + ca * p.y);
float2 cs = lerp(float2(160.0, 110.0), float2(520.0, 340.0), g.h(blk + 9.1));
float2 c = floor(q / cs); float2 f = frac(q / cs);
float hc = g.h(c + blk * 7.0);
float sp = 0.3 + 0.4 * g.h(c + 51.3);
float side = (hc > 0.5) ? step(sp, f.x) : step(sp, f.y);
float id = g.h(c * 1.7 + side * 13.1 + 7.0);
float3 fc = id < 0.20 ? float3(0.085, 0.095, 0.030) : id < 0.38 ? float3(0.130, 0.120, 0.055) : id < 0.60 ? float3(0.165, 0.110, 0.060) : id < 0.80 ? float3(0.260, 0.205, 0.120) : float3(0.205, 0.165, 0.110);
fc *= 0.88 + 0.24 * g.vn(q / 50.0 + id * 31.0);
float2 e = min(f, 1.0 - f) * cs;
float eb = min(e.x, e.y);
eb = (hc > 0.5) ? min(eb, abs(f.x - sp) * cs.x) : min(eb, abs(f.y - sp) * cs.y);
float border = (1.0 - smoothstep(2.0, 2.0 + px, eb)) * saturate(4.0 / px);
fc = lerp(fc, float3(0.21, 0.19, 0.16), border * 0.6);
fc = lerp(fc, float3(0.170, 0.140, 0.080), far);
// arid hills: tan with darker wadis/scrub
float3 ar = lerp(float3(0.32, 0.25, 0.16), float3(0.18, 0.14, 0.09), g.fbm(p / 800.0));
ar *= 0.88 + 0.24 * lerp(g.fbm(p / 90.0 + 5.0), 0.5, smoothstep(10.0, 60.0, px));
float3 col = lerp(ar, fc, farm);
// towns
if (g.h(floor(p / 1500.0) + 91.0) > 0.94) {
  float tr = 1.0 - smoothstep(0.10, 0.30, length(frac(p / 1500.0) - 0.5) + 0.18 * (g.fbm(p / 120.0 + 33.0) - 0.5));
  float3 tc = lerp(lerp(float3(0.24, 0.22, 0.20), float3(0.38, 0.35, 0.31), g.h(floor(p / 25.0))), float3(0.27, 0.25, 0.22), far);
  col = lerp(col, tc, tr * 0.7);
}
return col;
"""

mp = MATDIR + "/M_Ground"
# rebuild in place: deleting a material that is in use crashes the editor
if eal.does_asset_exist(mp):
    m = eal.load_asset(mp); mel.delete_all_material_expressions(m)
else:
    m = at.create_asset("M_Ground", MATDIR, unreal.Material, unreal.MaterialFactoryNew())
E = lambda cls, x, y: mel.create_material_expression(m, cls, x, y)
wp = E(unreal.MaterialExpressionWorldPosition, -900, 0)
cu = E(unreal.MaterialExpressionCustom, -500, 0)
cu.set_editor_property("code", CODE)
cu.set_editor_property("output_type", unreal.CustomMaterialOutputType.CMOT_FLOAT3)
cu.set_editor_property("description", "ProceduralGround")
ins = []
for n in ["WP", "Cam"]:
    ci = unreal.CustomInput(); ci.set_editor_property("input_name", n); ins.append(ci)
cu.set_editor_property("inputs", ins)
mel.connect_material_expressions(wp, "", cu, "WP")
cam = E(unreal.MaterialExpressionCameraPositionWS, -900, 150)
mel.connect_material_expressions(cam, "", cu, "Cam")
m.set_editor_property("two_sided", True)
rough = E(unreal.MaterialExpressionConstant, -300, 200); rough.set_editor_property("r", 0.95)
mel.connect_material_property(cu, "", unreal.MaterialProperty.MP_BASE_COLOR)
mel.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
mel.recompile_material(m); eal.save_loaded_asset(m)

for a in eas.get_all_level_actors():
    if a.get_actor_label() == "Ground": eas.destroy_actor(a)
t = unreal.AssetImportTask()
t.filename = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir()), "Data", "Generated", "ground_cap.obj")
t.destination_path = MESHDIR; t.destination_name = "SM_GroundCap"; t.automated = True; t.replace_existing = True; t.save = True
at.import_asset_tasks([t])
mesh = eal.load_asset(MESHDIR + "/SM_GroundCap")
ns = mesh.get_editor_property("nanite_settings")
if ns.get_editor_property("enabled"):   # Nanite on a 600 km mesh cracks along cluster edges (streaks near the horizon)
    ns.set_editor_property("enabled", False); mesh.set_editor_property("nanite_settings", ns); eal.save_loaded_asset(mesh)
bb = mesh.get_bounding_box(); log("mesh bounds min %s max %s" % (bb.min, bb.max))
g = eas.spawn_actor_from_class(unreal.StaticMeshActor, unreal.Vector(0, 0, Z))
g.set_actor_label("Ground")
smc = g.static_mesh_component
smc.set_static_mesh(mesh)
smc.set_material(0, m)
smc.set_editor_property("cast_shadow", False)
smc.set_editor_property("affect_distance_field_lighting", False)
smc.set_editor_property("affect_dynamic_indirect_lighting", False)   # keep the 600 km cap out of the Lumen scene
smc.set_editor_property("visible_in_ray_tracing", False)
smc.set_collision_enabled(unreal.CollisionEnabled.NO_COLLISION)
log("ground cap at z=%.0f" % Z)

sky = next(a for a in eas.get_all_level_actors() if isinstance(a, unreal.SkyAtmosphere)).get_component_by_class(unreal.SkyAtmosphereComponent)
sky.modify()
srgb = lambda v: int(round(255 * (12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055)))
sky.set_editor_property("aerial_pespective_view_distance_scale", 2.0)   # was 4: ground 6 km down was washed out blue
sky.set_editor_property("ground_albedo", unreal.Color(r=srgb(FAR[0]), g=srgb(FAR[1]), b=srgb(FAR[2]), a=255))
log("ground albedo %s" % sky.get_editor_property("ground_albedo"))
unreal.get_editor_subsystem(unreal.LevelEditorSubsystem).save_current_level()
log("done")
